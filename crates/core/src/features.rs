#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Category {
    Gpu,
    Graphics,
    Cpu,
    Windows,
    Radeon,
    Upscaling,
    Omen,
}
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ValueKind {
    Integer,
    Boolean,
    Choice,
    VfCurve,
    PerCore,
    CoreRatios,
    FanCurve,
    Colors,
}
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Unit {
    None,
    Mhz,
    Millivolt,
    Milliwatt,
    Celsius,
    FramesPerSecond,
    Seconds,
    Milliampere,
    CurveStep,
    Hz,
    Percent,
}

#[derive(Debug, Serialize)]
pub struct Descriptor {
    pub feature: Feature,
    pub category: Category,
    pub value_kind: ValueKind,
    pub unit: Unit,
}

